"""Write firmware/src/vibe_tables.h: the constant tables vibe.c needs (the chip has no FPU, so every curve that
needs exp/log is computed here, on the computer, and lands in flash as integers).

  python3 tools/gen_vibe_tables.py            (run from fm1/; the header is committed, rerun only when a curve changes)
"""
import math
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parents[1] / "firmware" / "src" / "vibe_tables.h"


def row(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


# knob 0..127 -> Hz, 40 .. 12000 exponential (noise filters, wind/earth centres)
freq = [round(40 * 300 ** (i / 127)) for i in range(128)]
# decay index 0..63 -> per-32-frame multiplier (Q15) for a T60 of 0.1 .. 30 s
dec = []
for i in range(64):
    t60 = 0.1 * 300 ** (i / 63)
    dec.append(min(32767, round(32768 * 10 ** (-3 * 32 / (t60 * FS)))))
# pulse knob 0..127 -> LFO phase step per 32-frame block, 0.25 .. 12 Hz (0 = off, handled in vibe.c)
pulse = [round(0.25 * 48 ** (i / 127) * 2 ** 32 * 32 / FS) for i in range(128)]

OUT.write_text(f"""/* SPDX-License-Identifier: GPL-3.0-only */
/* Generated by tools/gen_vibe_tables.py: do not edit by hand. */
#ifndef VIBE_TABLES_H
#define VIBE_TABLES_H

static const uint16_t FREQ_HZ[128] = {{   /* knob -> Hz, 40 .. 12000 exponential */
{row(freq)}
}};

static const uint16_t DEC32[64] = {{       /* T60 0.1 .. 30 s -> Q15 multiplier per 32 frames */
{row(dec)}
}};

static const uint32_t PULSE_INC[128] = {{  /* knob -> phase step per 32 frames, 0.25 .. 12 Hz */
{row(pulse, 8)}
}};

#endif
""")
print("->", OUT)
